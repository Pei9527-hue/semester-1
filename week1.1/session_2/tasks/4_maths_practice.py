# 1: (4 x 8) x 6
# In Python, multiplication is reprented by the asterisk (*)
result1 = (4 * 8) * 6
print(f"1: (4 * 8) * 6 = {result1}")

# 2: (2^3) / (8/3)
# Note: In Python,the caret symbol (^) does not represcent power.We must use double asterisks (**)
